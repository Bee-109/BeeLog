begin;

create or replace function public.is_beelog_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;
revoke all on function public.is_beelog_admin() from public;
grant execute on function public.is_beelog_admin() to anon, authenticated;

create table if not exists public.project_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#e8b85a',
  icon text not null default '◈',
  created_at timestamptz not null default now()
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.project_categories(id) on delete restrict,
  name text not null,
  description text not null default '',
  cover_image text,
  status text not null default 'draft' check (status in ('draft','published')),
  created_at timestamptz not null default now(),
  published_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists public.devlogs (
  id bigint generated by default as identity primary key,
  project_id bigint references public.projects(id) on delete set null,
  title text not null,
  description text not null default '',
  cover_image text not null default '',
  image_count integer not null default 0 check (image_count >= 0),
  video_count integer not null default 0 check (video_count >= 0),
  status text not null default 'draft' check (status in ('draft','published')),
  created_at timestamptz not null default now(),
  published_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#e8b85a',
  created_at timestamptz not null default now()
);
create table if not exists public.project_tags (
  project_id bigint not null references public.projects(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (project_id, tag_id)
);
create table if not exists public.devlog_tags (
  devlog_id bigint not null references public.devlogs(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (devlog_id, tag_id)
);
create table if not exists public.media (
  id bigint generated by default as identity primary key,
  project_id bigint references public.projects(id) on delete set null,
  devlog_id bigint references public.devlogs(id) on delete set null,
  name text not null,
  storage_path text not null,
  media_type text not null check (media_type in ('image','video')),
  status text not null default 'draft' check (status in ('draft','published')),
  created_at timestamptz not null default now(),
  published_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists public.admin_activity (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null check (action in ('created','edited','deleted')),
  entity_type text not null check (entity_type in ('Devlog','Tag','Category','Project','Media')),
  title text not null,
  context text not null default '',
  details text not null default '',
  before_after jsonb,
  created_at timestamptz not null default now()
);

alter table public.project_categories enable row level security;
alter table public.projects enable row level security;
alter table public.devlogs enable row level security;
alter table public.tags enable row level security;
alter table public.project_tags enable row level security;
alter table public.devlog_tags enable row level security;
alter table public.media enable row level security;
alter table public.admin_activity enable row level security;

revoke all on public.project_categories, public.projects, public.devlogs, public.tags,
  public.project_tags, public.devlog_tags, public.media, public.admin_activity from anon, authenticated;
grant select on public.project_categories, public.projects, public.devlogs, public.tags,
  public.project_tags, public.devlog_tags, public.media to anon, authenticated;
grant insert, update, delete on public.project_categories, public.projects, public.devlogs,
  public.tags, public.project_tags, public.devlog_tags, public.media to authenticated;
grant select on public.admin_activity to authenticated;
grant usage, select on sequence public.project_categories_id_seq, public.projects_id_seq,
  public.devlogs_id_seq, public.tags_id_seq, public.media_id_seq, public.admin_activity_id_seq to authenticated;

create policy "published projects expose their categories" on public.project_categories for select to anon, authenticated
  using (public.is_beelog_admin() or exists (select 1 from public.projects p where p.category_id = id and p.status = 'published'));
create policy "admins manage categories" on public.project_categories for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());

create policy "public reads published projects" on public.projects for select to anon, authenticated
  using (status = 'published' or public.is_beelog_admin());
create policy "admins manage projects" on public.projects for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());

create policy "public reads published devlogs" on public.devlogs for select to anon, authenticated
  using (public.is_beelog_admin() or (status = 'published' and (project_id is null or exists (
    select 1 from public.projects p where p.id = project_id and p.status = 'published'))));
create policy "admins manage devlogs" on public.devlogs for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());

create policy "public reads tags used by published content" on public.tags for select to anon, authenticated
  using (public.is_beelog_admin()
    or exists (select 1 from public.project_tags pt join public.projects p on p.id = pt.project_id where pt.tag_id = id and p.status = 'published')
    or exists (select 1 from public.devlog_tags dt join public.devlogs d on d.id = dt.devlog_id where dt.tag_id = id and d.status = 'published'));
create policy "admins manage tags" on public.tags for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());

create policy "public reads tags on published projects" on public.project_tags for select to anon, authenticated
  using (public.is_beelog_admin() or exists (select 1 from public.projects p where p.id = project_id and p.status = 'published'));
create policy "admins manage project tags" on public.project_tags for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());
create policy "public reads tags on published devlogs" on public.devlog_tags for select to anon, authenticated
  using (public.is_beelog_admin() or exists (select 1 from public.devlogs d where d.id = devlog_id and d.status = 'published'));
create policy "admins manage devlog tags" on public.devlog_tags for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());

create policy "public reads published media" on public.media for select to anon, authenticated
  using (public.is_beelog_admin() or (status = 'published'
    and (project_id is null or exists (select 1 from public.projects p where p.id = project_id and p.status = 'published'))
    and (devlog_id is null or exists (select 1 from public.devlogs d where d.id = devlog_id and d.status = 'published'))));
create policy "admins manage media" on public.media for all to authenticated
  using (public.is_beelog_admin()) with check (public.is_beelog_admin());
create policy "admins read private activity" on public.admin_activity for select to authenticated
  using (public.is_beelog_admin());

-- Private object storage prevents draft assets from being fetched by URL.
insert into storage.buckets (id, name, public)
values ('beelog-media', 'beelog-media', false)
on conflict (id) do update set public = false;
create policy "published portfolio media can be read" on storage.objects for select to anon, authenticated
  using (bucket_id = 'beelog-media' and (public.is_beelog_admin() or exists (
    select 1 from public.media m where m.storage_path = name and m.status = 'published'
      and (m.project_id is null or exists (select 1 from public.projects p where p.id = m.project_id and p.status = 'published'))
      and (m.devlog_id is null or exists (select 1 from public.devlogs d where d.id = m.devlog_id and d.status = 'published')))));
create policy "admins upload portfolio media" on storage.objects for insert to authenticated
  with check (bucket_id = 'beelog-media' and public.is_beelog_admin());
create policy "admins update portfolio media files" on storage.objects for update to authenticated
  using (bucket_id = 'beelog-media' and public.is_beelog_admin())
  with check (bucket_id = 'beelog-media' and public.is_beelog_admin());
create policy "admins delete portfolio media files" on storage.objects for delete to authenticated
  using (bucket_id = 'beelog-media' and public.is_beelog_admin());

create or replace function public.record_beelog_activity()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  old_data jsonb;
  new_data jsonb;
  entity_name text;
  entity_title text;
  entity_context text := '';
  event_action text;
  change_details text;
begin
  if tg_op = 'DELETE' then old_data := to_jsonb(old); new_data := null; event_action := 'deleted';
  elsif tg_op = 'INSERT' then old_data := null; new_data := to_jsonb(new); event_action := 'created';
  else old_data := to_jsonb(old); new_data := to_jsonb(new); event_action := 'edited'; end if;
  entity_name := case tg_table_name when 'project_categories' then 'Category' when 'projects' then 'Project' when 'devlogs' then 'Devlog' when 'tags' then 'Tag' else 'Media' end;
  entity_title := coalesce(new_data->>'name', new_data->>'title', old_data->>'name', old_data->>'title', 'Untitled');
  if tg_table_name = 'projects' then
    select name into entity_context from public.project_categories where id = coalesce((new_data->>'category_id')::bigint, (old_data->>'category_id')::bigint);
  end if;
  if event_action = 'edited' then
    select string_agg(changed.key || ': ' || coalesce(old_data->>changed.key, '∅') || ' → ' || coalesce(new_data->>changed.key, '∅'), '; ')
      into change_details
      from jsonb_object_keys(new_data) as changed(key)
      where old_data->changed.key is distinct from new_data->changed.key
        and changed.key not in ('updated_at');
  else
    change_details := event_action || ' record.';
  end if;
  insert into public.admin_activity(actor_id, action, entity_type, title, context, details, before_after)
  values (auth.uid(), event_action, entity_name, entity_title, entity_context,
    coalesce(change_details, 'Record updated.'),
    jsonb_build_object('before', old_data, 'after', new_data));
  return coalesce(new, old);
end;
$$;

drop trigger if exists project_categories_activity on public.project_categories;
create trigger project_categories_activity after insert or update or delete on public.project_categories for each row execute function public.record_beelog_activity();
drop trigger if exists projects_activity on public.projects;
create trigger projects_activity after insert or update or delete on public.projects for each row execute function public.record_beelog_activity();
drop trigger if exists devlogs_activity on public.devlogs;
create trigger devlogs_activity after insert or update or delete on public.devlogs for each row execute function public.record_beelog_activity();
drop trigger if exists tags_activity on public.tags;
create trigger tags_activity after insert or update or delete on public.tags for each row execute function public.record_beelog_activity();
drop trigger if exists media_activity on public.media;
create trigger media_activity after insert or update or delete on public.media for each row execute function public.record_beelog_activity();

commit;
